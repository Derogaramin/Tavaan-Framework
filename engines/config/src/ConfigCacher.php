<?php

declare(strict_types=1);

namespace Tavaan\Engine\Config;

use Tavaan\Core\Contracts\Config\ConfigCacheInterface;
use Tavaan\Engine\Config\Exceptions\ConfigNotCacheableException;

/**
 * تَوان | Tavaan — Config
 * ConfigCacher — تولید/بارگذاری کش کل پیکربندی در یک فایل PHP (atomic write).
 *
 * @api 1.0
 * @see docs/03-engines/config.md
 */
final class ConfigCacher implements ConfigCacheInterface
{
    public function __construct(private readonly Repository $repository)
    {
    }

    public function cache(string $file): void
    {
        $all = $this->repository->all();
        $this->assertSerializable($all, '');

        $php = "<?php\n\n// Generated by `tvn config:cache` — DO NOT EDIT.\n// Generated at: "
            . \date('c') . "\n\nreturn " . \var_export($all, true) . ";\n";

        $this->write($file, $php);
    }

    /** @return array<string, mixed>|null */
    public function load(string $file): ?array
    {
        if (!\is_file($file)) {
            return null;
        }

        /** @var mixed $data */
        $data = require $file;

        return \is_array($data) ? $data : null;
    }

    public function clear(string $file): void
    {
        if (\is_file($file)) {
            @\unlink($file);
        }
        if (\function_exists('opcache_invalidate')) {
            \opcache_invalidate($file, true);
        }
    }

    public function isCached(string $file): bool
    {
        return \is_file($file);
    }

    /**
     * نوشتن اتمیک: temp + rename (جلوگیری از خواندن فایل ناقص).
     */
    private function write(string $path, string $content): void
    {
        $dir = \dirname($path);
        if (!\is_dir($dir)) {
            \mkdir($dir, 0775, true);
        }

        $tmp = $path . '.' . \bin2hex(\random_bytes(4)) . '.tmp';
        \file_put_contents($tmp, $content, LOCK_EX);
        \chmod($tmp, 0640);

        if (!\rename($tmp, $path)) {
            @\unlink($tmp);
            throw ConfigNotCacheableException::for($path, 'write_failed');
        }

        if (\function_exists('opcache_invalidate')) {
            \opcache_invalidate($path, true);
        }
    }

    /**
     * 🔒 Closure/resource/object در Config → غیرقابل کش.
     *
     * @param array<array-key, mixed> $data
     */
    private function assertSerializable(array $data, string $path): void
    {
        foreach ($data as $key => $value) {
            $keyPath = $path === '' ? (string) $key : $path . '.' . $key;

            if ($value instanceof \Closure) {
                throw ConfigNotCacheableException::for($keyPath, 'Closure');
            }
            if (\is_resource($value)) {
                throw ConfigNotCacheableException::for($keyPath, 'resource');
            }
            if (\is_object($value)) {
                throw ConfigNotCacheableException::for($keyPath, $value::class);
            }
            if (\is_array($value)) {
                $this->assertSerializable($value, $keyPath);
            }
        }
    }
}
