<?php

declare(strict_types=1);

namespace Tavaan\Engine\Container;

/**
 * تَوان | Tavaan — Container
 * ReflectionCache — کش امضای Constructorها (حافظه + فایل پایدار).
 *
 * 🔒 در PROD با `tvn container:compile` فایل کش load می‌شود → صفر Reflection سنگین.
 *
 * @api 1.0
 * @see docs/03-engines/container.md
 */
final class ReflectionCache
{
    /** @var array<string, ConstructorSignature> */
    private array $memory = [];

    /** @var array<string, array<string, mixed>>|null دادهٔ کش فایل */
    private ?array $file = null;

    /** @var array<string, \ReflectionClass<object>> */
    private array $reflections = [];

    /**
     * @param class-string $class
     */
    public function signatureOf(string $class): ConstructorSignature
    {
        if (isset($this->memory[$class])) {
            return $this->memory[$class];
        }

        if ($this->file !== null && isset($this->file[$class])) {
            return $this->memory[$class] = ConstructorSignature::fromArray($this->file[$class]);
        }

        return $this->memory[$class] = $this->introspect($class);
    }

    /**
     * ReflectionClass (سبک — فقط برای newInstanceArgs).
     *
     * @param class-string $class
     *
     * @return \ReflectionClass<object>
     */
    public function reflectionOf(string $class): \ReflectionClass
    {
        return $this->reflections[$class] ??= new \ReflectionClass($class);
    }

    /**
     * @param class-string $class
     */
    private function introspect(string $class): ConstructorSignature
    {
        if (!\class_exists($class)) {
            throw Exceptions\BindingResolutionException::classNotFound($class);
        }

        $ref = $this->reflectionOf($class);
        $ctor = $ref->getConstructor();

        if ($ctor === null) {
            return new ConstructorSignature($class, false, [], $ref->isInstantiable());
        }

        $params = [];
        foreach ($ctor->getParameters() as $p) {
            $params[] = ParameterSignature::fromReflection($p);
        }

        return new ConstructorSignature($class, true, $params, $ref->isInstantiable());
    }

    /** نوشتن کش به فایل (var_export — atomic). */
    public function dump(string $file): void
    {
        $data = [];
        foreach ($this->memory as $class => $signature) {
            $data[$class] = $signature->toArray();
        }
        \ksort($data);

        $dir = \dirname($file);
        if (!\is_dir($dir)) {
            \mkdir($dir, 0775, true);
        }

        $content = "<?php\n\n// Generated by `tvn container:compile` — DO NOT EDIT.\n\nreturn "
            . \var_export($data, true) . ";\n";

        $tmp = $file . '.' . \bin2hex(\random_bytes(4)) . '.tmp';
        \file_put_contents($tmp, $content, LOCK_EX);
        \rename($tmp, $file);

        if (\function_exists('opcache_invalidate')) {
            \opcache_invalidate($file, true);
        }
    }

    /** بارگذاری کش فایل. */
    public function load(string $file): void
    {
        if (!\is_file($file)) {
            return;
        }

        /** @var array<string, array<string, mixed>> $data */
        $data = require $file;
        $this->file = $data;
    }

    public function count(): int
    {
        return \count($this->memory) + ($this->file === null ? 0 : \count($this->file));
    }
}
