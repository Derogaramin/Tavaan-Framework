<?php

declare(strict_types=1);

namespace Tavaan\Engine\Module;

use Tavaan\Core\Contracts\Events\DispatcherInterface;
use Tavaan\Engine\Module\Exceptions\ModuleException;

/**
 * تَوان | Tavaan — Module
 * ModuleManager — چرخهٔ عمر: install/enable/disable + پایداری وضعیت.
 *
 * @api 1.0
 * @see docs/03-engines/module.md
 */
final class ModuleManager
{
    public function __construct(
        private readonly ModuleRegistry $registry,
        private readonly string $statusFile,
        private readonly ?DispatcherInterface $events = null,
    ) {
    }

    public function enable(string $id): void
    {
        $module = $this->registry->get($id);

        // پیش‌نیازها باید فعال باشند
        foreach ($module->dependencies() as $dep) {
            if ($this->registry->has($dep) && !$this->registry->enabled($dep)) {
                throw new ModuleException(
                    messageId: 'module.dependency_disabled',
                    context: ['module' => $id, 'dependency' => $dep],
                    hint: 'ابتدا ماژول پیش‌نیاز را فعال کنید.',
                );
            }
        }

        $this->registry->setEnabled($id, true);
        $this->persist();
        $this->events?->dispatch('module.enabled', ['module' => $module->id()]);
    }

    public function disable(string $id): void
    {
        $dependents = $this->registry->dependentsOf($id);
        $activeDependents = [];
        foreach ($dependents as $dep) {
            if ($this->registry->enabled($dep)) {
                $activeDependents[] = $dep;
            }
        }

        if ($activeDependents !== []) {
            throw ModuleException::hasDependents($id, $activeDependents);
        }

        $this->registry->setEnabled($id, false);
        $this->persist();
        $this->events?->dispatch('module.disabled', ['module' => $this->registry->get($id)->id()]);
    }

    /** اعتبارسنجی manifest همهٔ ماژول‌ها. @return list<string> خطاها (خالی = سالم) */
    public function validate(): array
    {
        $errors = [];
        foreach ($this->registry->all() as $module) {
            if ($module->version() === '') {
                $errors[] = $module->id() . ': version empty';
            }
        }

        try {
            $this->registry->sorted();
        } catch (\Throwable $e) {
            $errors[] = $e->getMessage();
        }

        return $errors;
    }

    /** نوشتن وضعیت در فایل پایدار. */
    private function persist(): void
    {
        $dir = \dirname($this->statusFile);
        if (!\is_dir($dir)) {
            \mkdir($dir, 0775, true);
        }

        $content = "<?php\n\n// Generated by tavaan module:enable/disable — DO NOT EDIT.\n\nreturn "
            . \var_export($this->registry->statusMap(), true) . ";\n";

        $tmp = $this->statusFile . '.' . \bin2hex(\random_bytes(4)) . '.tmp';
        \file_put_contents($tmp, $content, LOCK_EX);
        \rename($tmp, $this->statusFile);
    }
}
