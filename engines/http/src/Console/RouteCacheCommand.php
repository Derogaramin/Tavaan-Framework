<?php

declare(strict_types=1);

namespace Tavaan\Engine\Http\Console;

use Tavaan\Engine\Console\Command;
use Tavaan\Engine\Http\Routing\Router;

/**
 * کش روت‌ها (DOC-040 §5.6).
 *
 * @api 1.0
 * @see docs/03-engines/router.md
 */
final class RouteCacheCommand extends Command
{
    protected string $signature = 'route:cache';

    protected string $description = 'ذخیرهٔ روت‌های کامپایل‌شده در storage/cache/routes.php';

    public function handle(): int
    {
        /** @var Router $router */
        $router = $this->app->make('router');

        try {
            $routes = $router->toCacheArray();
        } catch (\LogicException $e) {
            $this->error('  ' . $e->getMessage());

            return self::FAILURE;
        }

        $file = (string) ($this->app->bound('config') ? $this->app->make('config')->get('router.cache.file', '') : '');
        if ($file === '') {
            $file = (\defined('TVN_BASE_PATH') ? (string) TVN_BASE_PATH : '') . '/storage/cache/routes.php';
        }

        $dir = \dirname($file);
        if (!\is_dir($dir)) {
            \mkdir($dir, 0775, true);
        }

        $content = "<?php\n\n// Generated by `tvn route:cache` — DO NOT EDIT.\n// Generated at: " . \date('c') . "\n\nreturn "
            . \var_export(['routes' => $routes], true) . ";\n";

        $tmp = $file . '.' . \bin2hex(\random_bytes(4)) . '.tmp';
        \file_put_contents($tmp, $content, LOCK_EX);
        \rename($tmp, $file);

        $this->info(\sprintf('  ✓ %d route(s) cached → %s', \count($routes), \basename($file)));

        return self::SUCCESS;
    }
}
