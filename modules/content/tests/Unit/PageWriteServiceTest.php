<?php

declare(strict_types=1);

namespace Modules\Content\Tests\Unit;

use Modules\Content\Application\UseCases\PageWriteService;
use Modules\Content\Domain\Entities\Page;
use Modules\Content\Domain\Enums\ContentStatus;
use Modules\Content\Domain\Repositories\PageRepositoryInterface;
use Modules\Content\Domain\Services\ExcerptGenerator;
use Modules\Content\Domain\Services\Markdown;
use Tavaan\Core\Exceptions\Validation\ValidationException;
use Tavaan\Testing\Database\RefreshDatabase;
use Tavaan\Testing\TestCase;

/**
 * تست PageWriteService — اعتبارسنجی، slug خودکار یونیک، رندر markdown،
 * سانیتیزه‌سازی، خلاصهٔ خودکار، چرخهٔ انتشار و حذف نرم.
 *
 * اپلیکیشن واقعی تست (tavaan_test_app) + SQLite in-memory — Facadeهای
 * Validator/Security/Event با binding واقعی.
 */
final class PageWriteServiceTest extends TestCase
{
    use RefreshDatabase;

    private \Tavaan\Core\Application\Application $app;

    private PageWriteService $service;

    private PageRepositoryInterface $pages;

    protected function setUp(): void
    {
        $this->app = \tavaan_test_app();
        $this->setUpDatabase();

        $config = $this->app->make('config');
        if ((string) $config->get('app.key', '') === '') {
            $config->set('app.key', 'base64:' . \base64_encode(\str_repeat('k', 32)));
        }
        $config->set('cache.default', 'array');

        $this->pages = $this->app->make(PageRepositoryInterface::class);
        $this->service = $this->app->make(PageWriteService::class);
    }

    // ─── ساخت صفحه ────────────────────────────────────────────────────────

    public function testCreateStoresDraftWithGeneratedSlug(): void
    {
        $page = $this->service->create([
            'title' => 'صفحهٔ دربارهٔ ما',
            'body' => "متن **سلام** برای آزمایش",
        ], authorId: 1);

        self::assertSame(ContentStatus::Draft, $page->status());
        self::assertNotSame('', $page->slug());
        self::assertSame(1, $page->authorId());

        $stored = $this->pages->findBySlug($page->slug());
        self::assertNotNull($stored);
        self::assertSame($page->id(), $stored->id());
        // markdown رندر شده است
        self::assertStringContainsString('<strong>', (string) $stored->body());
    }

    public function testCreateRequiresTitle(): void
    {
        try {
            $this->service->create(['title' => '', 'body' => 'بدنه'], authorId: 1);
            self::fail('باید ValidationException می‌انداخت');
        } catch (ValidationException $e) {
            self::assertArrayHasKey('title', $e->errors);
        }
    }

    public function testDuplicateTitleGetsUniqueSlug(): void
    {
        $first = $this->service->create(['title' => 'صفحهٔ تکراری'], authorId: 1);
        $second = $this->service->create(['title' => 'صفحهٔ تکراری'], authorId: 1);

        self::assertNotSame($first->slug(), $second->slug());
        self::assertNotNull($this->pages->findBySlug($second->slug()));
    }

    public function testExplicitSlugHonored(): void
    {
        $page = $this->service->create([
            'title' => 'عنوان دلخواه',
            'slug' => 'custom-slug',
        ], authorId: 1);

        self::assertSame('custom-slug', $page->slug());
    }

    public function testCreateWithStatusPublishedPublishesImmediately(): void
    {
        $page = $this->service->create([
            'title' => 'انتشار فوری',
            'status' => 'published',
        ], authorId: 1);

        self::assertSame(ContentStatus::Published, $page->status());
        self::assertNotNull($page->publishedAt());
        self::assertTrue($this->pages->findBySlug($page->slug())?->isPublished() ?? false);
    }

    public function testCommentsOpenFlagPersisted(): void
    {
        $closed = $this->service->create([
            'title' => 'بدون نظر',
            'comments_open' => false,
        ], authorId: 1);
        self::assertFalse($closed->commentsOpenFlag());

        $open = $this->service->create(['title' => 'با نظر'], authorId: 1);
        self::assertTrue($open->commentsOpenFlag());
    }

    // ─── امنیت و رندر محتوا ──────────────────────────────────────────────

    public function testMarkdownRenderedAndScriptSanitized(): void
    {
        $page = $this->service->create([
            'title' => 'صفحهٔ امن',
            'body' => "# عنوان\n\n<script>alert(1)</script>سلام **دنیا**",
        ], authorId: 1);

        $body = (string) $this->pages->findById($page->id())?->body();
        self::assertStringContainsString('<h1', $body);
        self::assertStringContainsString('<strong>', $body);
        self::assertStringNotContainsString('<script>', $body);
    }

    public function testExcerptAutoGeneratedFromBody(): void
    {
        $longBody = \str_repeat('جملهٔ آزمایشی برای تولید خلاصه. ', 30);
        $page = $this->service->create([
            'title' => 'خلاصهٔ خودکار',
            'body' => $longBody,
        ], authorId: 1);

        $excerpt = (string) $page->excerpt();
        self::assertNotSame('', $excerpt);
        self::assertTrue(\mb_strlen($excerpt) < \mb_strlen($longBody));
    }

    public function testExplicitExcerptKept(): void
    {
        $page = $this->service->create([
            'title' => 'خلاصهٔ صریح',
            'body' => 'بدنهٔ کوتاه',
            'excerpt' => 'خلاصهٔ دستی من',
        ], authorId: 1);

        self::assertSame('خلاصهٔ دستی من', $page->excerpt());
    }

    public function testHtmlBodyFormatSanitizedToo(): void
    {
        $service = new PageWriteService(
            pages: $this->pages,
            markdown: $this->app->make(Markdown::class),
            excerpts: $this->app->make(ExcerptGenerator::class),
            config: [
                'body_format' => 'html',
                'sanitize' => [
                    'profile' => 'rich_text',
                    'extra_tags' => ['h1', 'h4', 'h5', 'h6', 'del', 'hr', 'figure', 'figcaption'],
                ],
            ],
        );

        $page = $service->create([
            'title' => 'فرمت اچ‌تی‌ام‌ال',
            'body' => '<p>سلام</p><script>alert(2)</script><h1>عنوان</h1>',
        ], authorId: 1);

        $body = (string) $this->pages->findById($page->id())?->body();
        self::assertStringContainsString('<p>سلام</p>', $body);
        self::assertStringContainsString('<h1>', $body);
        self::assertStringNotContainsString('<script>', $body);
    }

    // ─── ویرایش ──────────────────────────────────────────────────────────

    public function testUpdateChangesFieldsAndKeepsAuthor(): void
    {
        $page = $this->service->create(['title' => 'عنوان قدیم', 'body' => 'قدیم'], authorId: 42);

        $updated = $this->service->update($page, [
            'title' => 'عنوان نو',
            'body' => 'متن **نو**',
        ]);

        self::assertSame('عنوان نو', $updated->title());
        self::assertSame(42, $updated->authorId());
        self::assertNotNull($updated->updatedAt());

        $stored = $this->pages->findById($page->id());
        self::assertNotNull($stored);
        self::assertSame('عنوان نو', $stored->title());
        self::assertStringContainsString('<strong>', (string) $stored->body());
    }

    public function testUpdateToExistingSlugGetsUniquified(): void
    {
        $a = $this->service->create(['title' => 'صفحهٔ الف', 'slug' => 'page-a'], authorId: 1);
        $b = $this->service->create(['title' => 'صفحهٔ ب', 'slug' => 'page-b'], authorId: 1);

        $this->service->update($b, ['title' => 'صفحهٔ ب', 'slug' => 'page-a']);

        self::assertNotSame($a->slug(), $this->pages->findById($b->id())?->slug());
    }

    // ─── چرخهٔ وضعیت ─────────────────────────────────────────────────────

    public function testPublishArchiveLifecycle(): void
    {
        $page = $this->service->create(['title' => 'چرخهٔ حیات'], authorId: 1);

        $this->service->publish($page);
        self::assertSame('published', $this->pages->findById($page->id())?->status()->value);

        $this->service->archive($page);
        self::assertSame('archived', $this->pages->findById($page->id())?->status()->value);

        $this->service->backToDraft($page);
        self::assertSame('draft', $this->pages->findById($page->id())?->status()->value);
    }

    public function testPublishFromArchivedThrows(): void
    {
        $page = $this->service->create(['title' => 'غیرقابل انتشار'], authorId: 1);
        $this->service->publish($page);
        $this->service->archive($page);

        $this->expectException(\DomainException::class);
        $this->service->publish($page);
    }

    // ─── حذف نرم/سخت ─────────────────────────────────────────────────────

    public function testTrashSoftDeletesAndForceDeleteRemoves(): void
    {
        $page = $this->service->create(['title' => 'حذف‌شونده'], authorId: 1);
        $id = $page->id();

        $this->service->trash($page);
        $trashed = $this->pages->findById($id);
        self::assertNotNull($trashed);
        self::assertTrue($trashed->isTrashed());
        self::assertNull($this->pages->findBySlug($page->slug()));            // بدون trash
        self::assertNotNull($this->pages->findBySlug($page->slug(), true));   // با trash

        $this->service->forceDelete($trashed);
        self::assertNull($this->pages->findById($id));
    }

    public function testForceDeleteOnLivePageThrows(): void
    {
        $page = $this->service->create(['title' => 'زنده'], authorId: 1);

        $this->expectException(\DomainException::class);
        $this->service->forceDelete($page);
    }

    // ─── SEO ─────────────────────────────────────────────────────────────

    public function testSeoFieldsStoredAndDefaulted(): void
    {
        $explicit = $this->service->create([
            'title' => 'صفحهٔ سئو',
            'body' => 'بدنهٔ سئو',
            'seo_title' => 'عنوان سئوی سفارشی',
            'seo_description' => 'توضیح سئوی سفارشی',
            'seo_keywords' => 'seo, test',
        ], authorId: 1);

        $stored = $this->pages->findById($explicit->id());
        self::assertNotNull($stored);
        self::assertSame('عنوان سئوی سفارشی', $stored->seo()->title);
        self::assertSame('توضیح سئوی سفارشی', $stored->seo()->description);
        self::assertSame('seo, test', $stored->seo()->keywords);

        // بدون فیلد صریح → description از خلاصه/عنوان ساخته می‌شود
        $implicit = $this->service->create(['title' => 'بدون سئو'], authorId: 1);
        self::assertNotSame('', $implicit->seo()->description);
    }

    public function testCountPublishedReflectsLifecycle(): void
    {
        self::assertSame(0, $this->pages->countPublished());

        $page = $this->service->create(['title' => 'شمارش'], authorId: 1);
        self::assertSame(0, $this->pages->countPublished());

        $this->service->publish($page);
        self::assertSame(1, $this->pages->countPublished());

        $this->service->trash($page);
        self::assertSame(0, $this->pages->countPublished());
    }

    public function testLatestPublishedOnlyReturnsPublished(): void
    {
        $draft = $this->service->create(['title' => 'پیش‌نویس مانده'], authorId: 1);
        $live = $this->service->create(['title' => 'منتشر شده'], authorId: 1);
        $this->service->publish($live);

        $rows = $this->pages->latestPublished(10);
        self::assertCount(1, $rows);
        self::assertSame($live->id(), $rows[0]->id());
        self::assertNotSame($draft->id(), $rows[0]->id());
        self::assertInstanceOf(Page::class, $rows[0]);
    }
}
