<?php

declare(strict_types=1);

namespace Tavaan\Core\Autoloading;

/**
 * تَوان | Tavaan — Core
 * ClassMapGenerator — اسکن دایرکتوری‌ها و تولید نگاشت FQCN → file برای کش.
 *
 * @api 1.0
 * @see docs/02-architecture/bootstrapping.md
 */
final class ClassMapGenerator
{
    /** @var list<string> بخشهای مسیر که همیشه حذف می‌شوند */
    private const SKIP_DIRS = ['tests', 'Tests', 'docs', 'examples', 'benchmarks', 'Fixtures', 'vendor', 'node_modules'];

    /**
     * @param list<string> $excludePatterns الگوهای اضافی (مانند الگوی tests در هر شاخه)
     */
    public function __construct(private readonly array $excludePatterns = [])
    {
    }

    /**
     * تولید ClassMap از همهٔ نگاشت‌های ثبت‌شده.
     *
     * @param array<string, list<string>> $prefixes
     * @param array<string, list<string>> $wildcards
     *
     * @return array<string, string>
     */
    public function generate(array $prefixes, array $wildcards, string $basePath): array
    {
        $map = [];

        foreach ($prefixes as $prefix => $dirs) {
            foreach ($dirs as $dir) {
                if (!\is_dir($dir)) {
                    continue;
                }
                foreach ($this->scanDirectory($dir, $prefix) as $class => $file) {
                    $map[$class] = $file;
                }
            }
        }

        foreach ($wildcards as $prefix => $patterns) {
            foreach ($patterns as $pattern) {
                $globPattern = \str_contains($pattern, '*') ? $pattern : $pattern;
                foreach (\glob($globPattern, GLOB_ONLYDIR) ?: [] as $dir) {
                    $engineName = $this->dirNameToNamespace($dir, $pattern);
                    foreach ($this->scanDirectory($dir, $prefix . $engineName . '\\') as $class => $file) {
                        $map[$class] = $file;
                    }
                }
            }
        }

        \ksort($map);

        return $map;
    }

    /**
     * اسکن بازگشتی یک دایرکتوری.
     *
     * @return array<string, string> FQCN → مسیر مطلق
     */
    public function scanDirectory(string $dir, string $prefix): array
    {
        $map = [];
        $dir = \rtrim($dir, '/');

        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveCallbackFilterIterator(
                new \RecursiveDirectoryIterator($dir, \FilesystemIterator::SKIP_DOTS),
                function (\SplFileInfo $file): bool {
                    if ($file->isDir()) {
                        return !\in_array($file->getFilename(), self::SKIP_DIRS, true);
                    }

                    return $file->getExtension() === 'php';
                },
            ),
        );

        /** @var \SplFileInfo $file */
        foreach ($iterator as $file) {
            $relative = \substr($file->getPathname(), \strlen($dir) + 1);
            $relative = \str_replace('\\', '/', $relative);

            if ($this->isExcluded($relative)) {
                continue;
            }

            $class = $prefix . \str_replace('/', '\\', \substr($relative, 0, -4));

            // 🔒 اعتبارسنجی: فایل واقعاً همان کلاس/namespace را declare کرده باشد
            // (helpers.php بدون کلاس و namespaceهای نامنطبق حذف می‌شوند)
            if (!$this->fileDeclares($file->getPathname(), $class)) {
                continue;
            }

            $map[$class] = $file->getPathname();
        }

        return $map;
    }

    /**
     * نوشتن اتمیک ClassMap به‌صورت فایل PHP (`return [...]`).
     *
     * @param array<string, string> $map
     */
    public static function writePhpArray(string $file, array $map): void
    {
        $dir = \dirname($file);
        if (!\is_dir($dir)) {
            \mkdir($dir, 0775, true);
        }

        $content = "<?php\n\n// Generated by `tvn autoload:cache` — DO NOT EDIT.\n// Generated at: "
            . \date('c') . "\n\nreturn " . \var_export($map, true) . ";\n";

        $tmp = $file . '.' . \bin2hex(\random_bytes(4)) . '.tmp';
        \file_put_contents($tmp, $content, LOCK_EX);
        \chmod($tmp, 0644);

        if (!\rename($tmp, $file)) {
            @\unlink($tmp);
            throw new \RuntimeException(\sprintf('Unable to write classmap cache to "%s".', $file));
        }

        if (\function_exists('opcache_invalidate')) {
            \opcache_invalidate($file, true);
        }
    }

    /**
     * استخراج بخشی از مسیر که جای `*` نشسته و تبدیل kebab → Pascal.
     *
     * مثال: pattern=`/app/engines/*&#47;src`, dir=`/app/engines/http-client/src` → `HttpClient`.
     */
    private function dirNameToNamespace(string $dir, string $pattern): string
    {
        $parts = \explode('*', $pattern, 2);
        if (\count($parts) !== 2) {
            return \str_replace(' ', '', \ucwords(\str_replace(['-', '_'], ' ', \basename($dir))));
        }

        [$before, $after] = $parts;
        $start = \strlen($before);
        $length = \strlen($dir) - $start - \strlen($after);
        $name = $length > 0 ? \substr($dir, $start, $length) : \basename($dir);

        return \str_replace(' ', '', \ucwords(\str_replace(['-', '_'], ' ', $name)));
    }

    /**
     * بررسی سبک (regex روی محتوای فایل) که آیا فایل، کلاس مورد انتظار را declare می‌کند.
     */
    private function fileDeclares(string $path, string $expectedClass): bool
    {
        $contents = \file_get_contents($path);
        if ($contents === false) {
            return false;
        }

        $parts = \explode('\\', $expectedClass);
        $className = \array_pop($parts);
        $namespace = \implode('\\', $parts);

        // class|interface|trait|enum با نام مورد انتظار
        if (\preg_match('/^\s*(?:(?:final|abstract|readonly)\s+)*(?:class|interface|trait|enum)\s+' . \preg_quote($className, '/') . '\b/m', $contents) !== 1) {
            return false;
        }

        // namespace منطبق
        return \preg_match('/^\s*namespace\s+' . \preg_quote($namespace, '/') . '\s*;/m', $contents) === 1;
    }

    private function isExcluded(string $relativePath): bool
    {
        foreach ($this->excludePatterns as $pattern) {
            $regex = '#^' . \str_replace('\*', '.*', \preg_quote($pattern, '#')) . '$#';
            if (\preg_match($regex, $relativePath) === 1) {
                return true;
            }
        }

        return false;
    }
}
